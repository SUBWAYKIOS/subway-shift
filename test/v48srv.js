const nItems = S.tpl.slots.reduce((a, s) => a + s.items.length, 0);
ok('tổng ' + nItems + ' mục', nItems >= 25);
ok('nhân viên xem ngày cũ → từ chối', /hôm nay/.test(err(() => api.hkState(t2, OLD))));
let r = api.hkTick(t2, TODAY, 'h11', true, 'e2bbbb');
ok('nhân viên tick → ghi giờ + tên', r.done.h11 && r.done.h11.by === 'e2bbbb' && r.done.h11.n === 'ラム' && r.done.h11.at > 0);
ok('tick lại không đổi giờ cũ', api.hkTick(t2, TODAY, 'h11', true, 'e2bbbb').done.h11.at === r.done.h11.at);
ok('tick bằng tên người khác → từ chối', /tên của mình/.test(err(() => api.hkTick(t2, TODAY, 'h12', true, 'e1aaaa'))));
ok('người khác bỏ tick của ラム → từ chối', /ラム/.test(err(() => api.hkTick(t1, TODAY, 'h11', false, 'e1aaaa'))));
