ok('ngày cũ → nhân viên không tick được', /hôm nay/.test(err(() => api.hkTick(t1, OLD, 'h51', true, 'e1aaaa'))));
r = api.hkTick(tok, OLD, 'h52', true, '', 'Lâm');
ok('quản lý tick hộ ngày cũ, kèm tên "Lâm"', r.done.h52 && r.done.h52.by === 'm' && r.done.h52.n === 'Lâm');
ok('quản lý bỏ được tick của nhân viên', !api.hkTick(tok, TODAY, 'h11', false, '').done.h11);
ok('mục không có trong mẫu → từ chối', /không còn/.test(err(() => api.hkTick(t2, TODAY, 'zz', true, 'e2bbbb'))));
ok('nhân viên không sửa mẫu được', /quản lý/i.test(err(() => api.hkTplSave(t2, '{"slots":[]}'))));
const tpl = JSON.parse(JSON.stringify(S.tpl));
tpl.slots[0].items.push({ t: { vi: 'Bật nhạc' } });
tpl.slots.push({ at: '9:5', t: { vi: 'giờ sai' }, items: [] });
